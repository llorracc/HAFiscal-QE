_ORIG_AGG_SOLVE = AggregateDemandEconomy.solve

# Persistent module-level worker Pool. Created on first call to
# _parallel_agg_solve with _SOLVE_WORKERS > 1 and reused across all
# subsequent eco.solve() calls in the same process. Eliminates the
# 60-120 s/iter spawn overhead seen in the parallel3+spawn experiment
# (workers re-import HARK + re-JIT JAX kernels each time a fresh Pool
# was created). Workers stay warm across AD outer iters and keep their
# JIT cache populated.
_PERSISTENT_POOL = None
_PERSISTENT_POOL_SIZE = 0


def _cleanup_persistent_pool():
    """atexit cleanup for the persistent Pool."""
    global _PERSISTENT_POOL, _PERSISTENT_POOL_SIZE
    if _PERSISTENT_POOL is not None:
        try:
            _PERSISTENT_POOL.terminate()
            _PERSISTENT_POOL.join()
        except Exception:
            pass
        _PERSISTENT_POOL = None
        _PERSISTENT_POOL_SIZE = 0


def _get_persistent_pool(n_workers):
    """Lazily create a spawn-context Pool of n_workers workers. If the pool
    already exists at the right size, reuse it; if size differs, recreate."""
    global _PERSISTENT_POOL, _PERSISTENT_POOL_SIZE
    import atexit
    if _PERSISTENT_POOL is not None and _PERSISTENT_POOL_SIZE == n_workers:
        return _PERSISTENT_POOL
    # Need to (re)create
    if _PERSISTENT_POOL is not None:
        _cleanup_persistent_pool()
    mp_ctx = multiprocessing.get_context("spawn")
    _PERSISTENT_POOL = mp_ctx.Pool(n_workers)
    _PERSISTENT_POOL_SIZE = n_workers
    # Register cleanup the first time we create the pool (atexit dedups by
    # function identity, so re-registering is harmless)
    atexit.register(_cleanup_persistent_pool)
    return _PERSISTENT_POOL


def _parallel_agg_solve(self, warm_start=True):
    """Monkey-patched replacement for AggregateDemandEconomy.solve.

    When `_SOLVE_WORKERS <= 1`, defers to the original serial implementation.
    When `_SOLVE_WORKERS > 1`, uses a persistent module-level Pool of
    spawn-context workers (created on first use, reused across calls).
    Workers run 2B (HAFISCAL_USE_JAX_2B=1) or plain HARK solve_agent
    per cohort.
    """
    if _SOLVE_WORKERS <= 1:
        return _ORIG_AGG_SOLVE(self, warm_start=warm_start)

    # Prepare warm-start solutions in the parent. Also call pre_solve
    # here so the mutations are baked into the agent before it's pickled
    # off to a worker.
    payloads = []
    for i, agent in enumerate(self.agents):
        from_solution = None
        if warm_start and hasattr(agent, 'solution') and len(agent.solution) > 0:
            prev_sol = agent.solution[0]
            current_states = agent.MrkvArray[0].shape[0]
            prev_states = (
                len(prev_sol.vPfunc) if hasattr(prev_sol, 'vPfunc') else 0
            )
            if prev_states == current_states:
                from_solution = prev_sol
        agent.pre_solve()
        # Payload includes the agent itself (pickled to the worker);
        # spawn context doesn't inherit parent globals.
        payloads.append((i, agent, from_solution))

    # Load-balance: sort payloads by descending DiscFac (heuristic — high-β
    # cohorts have larger wealth → wider EGM grids → longer per-cohort
    # solve). With imap_unordered + chunksize=1, workers pick up next-largest
    # task as they finish previous ones, minimizing the longest-cohort tail.
    sorted_idx = sorted(range(len(payloads)),
                        key=lambda k: -float(payloads[k][1].DiscFac))
    payloads_sorted = [payloads[k] for k in sorted_idx]

    # Persistent Pool: reused across eco.solve() calls. First call creates
    # the workers (each ~10-30 s to import HARK + JAX); subsequent calls
    # dispatch directly to warm workers with hot JIT caches.
    pool = _get_persistent_pool(_SOLVE_WORKERS)
    results = list(pool.imap_unordered(
        _solve_agent_worker, payloads_sorted, chunksize=1))

    # Install solutions and run post_solve on the parent's agents.
    # imap_unordered returns in completion order, but each (idx, solution)
    # carries its own cohort index so order doesn't matter for assignment.
    for idx, solution in results:
        self.agents[idx].solution = solution
        self.agents[idx].post_solve()


# Install the monkey-patch at import time. Effect is process-local;
# AggFiscalModel.py on disk is unchanged.
AggregateDemandEconomy.solve = _parallel_agg_solve

